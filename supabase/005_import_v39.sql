insert into public.historical_records (stage_id, group_code, display_order, carry_names, lineup_label, credited_player)
select st.id, 'zero', source.row_no, string_to_array(source.carries, '/'), source.lineup, source.player
from source
join public.versions v on v.code = '3.9' and v.archived_at is null
join public.stages st on st.version_id = v.id and st.stage_no = source.stage_no
where not exists (
  select from public.submissions s
  where s.stage_id = st.id and s.group_code = 'zero'
    and s.status in ('pending', 'approved') and s.archived_at is null
    and lower(normalize(source.lineup, NFKC)) in (
      lower(normalize(array_to_string(s.team, ''), NFKC)),
      s.team_key
    )
)
on conflict (stage_id, group_code, lineup_key) do nothing;
